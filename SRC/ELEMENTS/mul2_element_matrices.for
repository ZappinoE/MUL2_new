     &                           EXPANSION_SPEC_TYPE,
     &                           FIND_KINEMATIC_INDEX,
     &                           FIELD_P, FIELD_T, N_SOLVED_FIELDS
      USE MUL2_EXPANSION_MESHES, ONLY: EXPANSION_DB_TYPE
